import { Group } from "three";
import { Ht, Se, U, et, nt } from "./decals.js";
import { vehicleMaterials } from "./materials.js";
import { Ne, Te, We, ws } from "./parts.js";
import { Mt } from "./wheels.js";

function buildCybercab() {
  const a = vehicleMaterials(),
    e = {
      R: 0.37,
      W: 0.235,
      rimR: 0.265,
      style: "cover",
      n: 14,
    },
    s = 1.3,
    t = -1.48,
    i = 0.405,
    o = Ne({
      zF: 2.15,
      zR: -2.15,
      rF: 0.44,
      pF: 2.3,
      rR: 0.34,
      pR: 2.7,
      rc: 0.05,
      kUp: 0.085,
      kDn: 0.07,
      soften: {
        f: 0.44,
        r: 0.3,
        n: 3.4,
      },
      arches: [
        {
          z: s,
          R: i,
          y: e.R,
        },
        {
          z: t,
          R: i,
          y: e.R,
        },
      ],
      extraStations: [1.3, -1.55],
      nose: {
        a: 0.27,
        k: 0.32,
        y: 0.45,
        q: 2.2,
      },
      tail: {
        a: 0.12,
        k: 0.75,
        y: 0.62,
        q: 2.4,
      },
      yt: [
        [2.15, 0.68],
        [1.9, 0.69],
        [1.65, 0.715],
        [1.45, 0.745],
        [1.33, 0.77],
        [1.15, 0.87],
        [0.9, 1.03],
        [0.6, 1.2],
        [0.3, 1.34],
        [0, 1.425],
        [-0.3, 1.44],
        [-0.65, 1.39],
        [-1, 1.29],
        [-1.35, 1.17],
        [-1.62, 1.075],
        [-1.85, 1.01],
        [-2, 0.975],
        [-2.15, 0.955],
      ],
      yBelt: [
        [2.15, 0.585],
        [1.9, 0.605],
        [1.6, 0.645],
        [1.3, 0.705],
        [0.9, 0.8],
        [0.3, 0.865],
        [-0.5, 0.88],
        [-1.2, 0.89],
        [-1.6, 0.895],
        [-2, 0.885],
        [-2.15, 0.88],
      ],
      ys: [
        [2.15, 0.48],
        [1, 0.53],
        [-1, 0.56],
        [-2.15, 0.6],
      ],
      yb: [
        [2.15, 0.18],
        [1.9, 0.16],
        [0, 0.15],
        [-1.85, 0.17],
        [-2.15, 0.2],
      ],
      wl: [
        [2.15, 0.88],
        [1.8, 0.95],
        [1.2, 0.972],
        [0, 0.975],
        [-1, 0.962],
        [-1.6, 0.93],
        [-2.15, 0.87],
      ],
      wgf: [
        [2.15, 0.99],
        [1.7, 0.99],
        [1.3, 0.82],
        [0.6, 0.86],
        [0, 0.88],
        [-0.6, 0.84],
        [-1.1, 0.72],
        [-1.55, 0.6],
        [-1.95, 0.93],
        [-2.15, 0.99],
      ],
      sh: [
        [2.15, 0.012],
        [1.3, 0.035],
        [0, 0.04],
        [-1.5, 0.035],
        [-2.15, 0.012],
      ],
      wr: [
        [2.15, 0.4],
        [1.3, 0.5],
        [0.5, 0.56],
        [0, 0.565],
        [-0.6, 0.5],
        [-1.1, 0.41],
        [-1.6, 0.33],
        [-2.15, 0.3],
      ],
      ng: [
        [2.15, 2.2],
        [1.35, 2.2],
        [1.05, 2.6],
        [0.3, 2.9],
        [-0.8, 2.7],
        [-1.5, 2.3],
        [-2.15, 2.2],
      ],
    }),
    n = new Group(),
    c = ws(o, a.gold, [-1.55, 1.3]);
  n.add(c);
  const r = Se(c),
    l = [];
  for (let p = 0; p <= 24; p++) {
    const w = -0.84 + (1.68 * p) / 24;
    l.push([w, 0.69 - 0.03 * Math.pow(Math.abs(w) / 0.84, 2.5)]);
  }
  n.add(
    et(r.front, U(l), 0.03, a.trim, {
      offset: 0.004,
    }),
  ),
    n.add(
      et(r.front, U(l), 0.012, a.lightW, {
        offset: 0.0065,
        wall: 0.002,
      }),
    ),
    n.add(
      et(
        r.front,
        U([
          [-0.6, 0.255],
          [0.6, 0.255],
        ]),
        0.022,
        a.trim,
        {
          offset: 0.003,
        },
      ),
    );
  const d = [];
  for (let p = 0; p <= 24; p++) {
    const w = -0.8 + (1.6 * p) / 24;
    d.push([w, 0.79 - 0.02 * Math.pow(Math.abs(w) / 0.8, 2.5)]);
  }
  n.add(
    et(r.rear, U(d), 0.045, a.lens, {
      offset: 0.004,
    }),
  ),
    n.add(
      et(r.rear, U(d), 0.015, a.lightR, {
        offset: 0.0068,
        wall: 0.002,
      }),
    ),
    n.add(
      nt(
        r.rear,
        [
          [-0.7, 0.3],
          [0.7, 0.3],
          [0.72, 0.42],
          [-0.72, 0.42],
        ],
        0.05,
        U,
        a.trim,
        {},
      ),
    );
  for (const p of [r.right, r.left])
    for (const w of [
      [
        [1, 0.32],
        [1.02, 0.8],
        [1.04, 0.86],
      ],
      [
        [-0.62, 0.3],
        [-0.64, 0.86],
      ],
    ])
      n.add(
        et(p, Ht(w), 0.004, a.seam, {
          offset: 0.002,
        }),
      );
  const f = 0.975 - e.W / 2 - 0.015;
  for (const p of [s, t])
    Mt(n, e, a.rimCover, f, p),
      Mt(n, e, a.rimCover, -f, p, !0),
      We(n, p, e.R, i - 0.005, f - e.W / 2 - 0.03, 0.12);
  return Te(n, "cybercab");
}

export { buildCybercab };
